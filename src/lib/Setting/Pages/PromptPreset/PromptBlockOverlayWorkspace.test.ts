    test('adds a dedicated full-width tab without renumbering existing destinations', () => {
        const settings = read('../PromptPresetSettings.svelte')

        expect(settings).toContain("{ label: language.promptOverlay.tab, value: 5 }")
        expect(settings).toContain('{ label: language.parameters, value: 3 }')
        expect(settings).toContain('{ label: language.advancedSettings, value: 4 }')
        expect(settings).toContain('<PromptBlockOverlayWorkspace />')
        expect(settings).toContain('$PromptPresetSubmenuIndex === 5')
    })

